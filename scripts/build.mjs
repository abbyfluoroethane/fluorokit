// Builds dist/ from tokens/ and src/.
//
//   dist/structure.css             spacing, shape, type scale and motion (--fk-*), in rem, and the root-size presets
//   dist/themes.json               every theme, as one list
//   dist/themes/<name>.css         one theme: colors and fonts (--fk-*)
//   dist/themes/<name>.shadcn.css  the same, plus the shadcn variable names
//   dist/themes/<name>.scoped.css  the theme and the shadcn names under [data-fk-theme="<name>"], not :root
//   dist/base.css                  type classes, status, the Metro page-enter
//   dist/tailwind.css              Tailwind 4 @theme mapping for shadcn projects
//   dist/shiki/<name>-<scheme>.json  a Shiki syntax theme, when the theme has syntax colors
//   dist/fonts/selawik.css         the Selawik font, for the zune theme
//   dist/tools/                    the theme recipe and the CSS writer, as modules
//   dist/enter.js                  setEnterDirection, for a direction-aware page-enter
//   dist/svelte/                   Svelte 5 components (Pivot)
//
// Every fluorokit variable has the --fk- prefix. The shadcn names (--muted,
// --accent ...) mean different things from the fluorokit names, so the two
// sets cannot share one namespace.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { REQUIRED, SHADCN, decls, shikiTheme, themeCss } from './theme-css.mjs';

const root = new URL('../', import.meta.url);
const read = (path) => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const write = (path, css) => writeFileSync(new URL(path, root), css);
const banner = (what) =>
  `/* fluorokit: ${what}. Generated by scripts/build.mjs. Do not edit by hand. */\n\n`;

function validate(theme, file) {
  const fail = (message) => {
    throw new Error(`${file}: ${message}`);
  };
  if (!theme.modes?.[theme.default]) fail(`default mode "${theme.default}" is not in modes`);
  if (theme.print && !theme.modes[theme.print]) fail(`print mode "${theme.print}" is not in modes`);
  for (const [key, mode] of Object.entries(theme.modes)) {
    if (!['light', 'dark'].includes(mode.colorScheme)) fail(`${key}: colorScheme must be light or dark`);
    const missing = REQUIRED.filter((token) => !(token in mode.colors));
    if (missing.length) fail(`${key}: missing colors ${missing.join(', ')}`);
    const unknown = Object.keys(mode.shadcn ?? {}).filter((name) => !(name in SHADCN));
    if (unknown.length) fail(`${key}: unknown shadcn names ${unknown.join(', ')}`);
  }
}

rmSync(new URL('dist/', root), { recursive: true, force: true });
mkdirSync(new URL('dist/themes/', root), { recursive: true });
mkdirSync(new URL('dist/shiki/', root), { recursive: true });

const structure = read('tokens/structure.json');
// The tokens, then the root-size presets (src/sizes.css), which do nothing
// unless the root element has data-fk-size.
write(
  'dist/structure.css',
  banner('spacing, shape, type scale, motion and root sizes') +
    `:root {\n${Object.values(structure).map((group) => decls(group, '  ')).join('\n')}}\n` +
    readFileSync(new URL('src/sizes.css', root), 'utf8'),
);

const themeFiles = readdirSync(new URL('tokens/themes/', root)).filter((f) => f.endsWith('.json'));
const allThemes = [];
for (const file of themeFiles) {
  const theme = read(`tokens/themes/${file}`);
  validate(theme, file);
  allThemes.push(theme);
  write(`dist/themes/${theme.name}.css`, themeCss(theme, false));
  write(`dist/themes/${theme.name}.shadcn.css`, themeCss(theme, true));
  write(`dist/themes/${theme.name}.scoped.css`, themeCss(theme, true, true));
  for (const [key, mode] of Object.entries(theme.modes)) {
    if (!mode.syntax || key === theme.print) continue;
    write(`dist/shiki/${theme.name}-${mode.colorScheme}.json`, JSON.stringify(shikiTheme(theme, key), null, 2) + '\n');
  }
}

write('dist/themes.json', JSON.stringify(allThemes, null, 2) + '\n');

// The recipe and the CSS writer, for a page that makes themes in the browser.
mkdirSync(new URL('dist/tools/', root), { recursive: true });
for (const file of ['color.mjs', 'fluoro.mjs', 'presets.mjs', 'theme-css.mjs']) {
  cpSync(new URL(`scripts/${file}`, root), new URL(`dist/tools/${file}`, root));
}

for (const file of ['base.css', 'tailwind.css', 'enter.js', 'enter.d.ts', 'svelte', 'fonts']) {
  cpSync(new URL(`src/${file}`, root), new URL(`dist/${file}`, root), { recursive: true });
}

console.log(`fluorokit: ${themeFiles.length} themes, ${Object.values(structure).flatMap(Object.keys).length} structure tokens`);
