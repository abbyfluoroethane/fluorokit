// Turns a theme (the JSON in tokens/themes) into CSS and into a Shiki syntax
// theme. It reads no files, so that a page can use it in the browser.

const banner = (what) =>
  `/* fluorokit: ${what}. Generated by scripts/build.mjs. Do not edit by hand. */\n\n`;

// shadcn name -> fluorokit color token. A mode can replace any entry with a
// literal value in its "shadcn" object.
export const SHADCN = {
  background: 'base',
  foreground: 'text',
  card: 'mantle',
  'card-foreground': 'text',
  popover: 'mantle',
  'popover-foreground': 'text',
  primary: 'accent',
  'primary-foreground': 'on-accent',
  secondary: 'raised',
  'secondary-foreground': 'text',
  muted: 'deep',
  'muted-foreground': 'muted',
  accent: 'hover',
  'accent-foreground': 'text',
  destructive: 'status-error',
  border: 'line',
  input: 'control-border',
  ring: 'focus',
  'chart-1': 'chart-1',
  'chart-2': 'chart-2',
  'chart-3': 'chart-3',
  'chart-4': 'chart-4',
  'chart-5': 'chart-5',
};

export const REQUIRED = [
  'base', 'mantle', 'deep', 'raised', 'line', 'overlay', 'text', 'muted',
  'accent', 'on-accent', 'link-underline', 'bar-start', 'bar-end', 'focus',
  'control-border', 'hover', 'selection', 'disabled',
  'status-error', 'on-error', 'status-warn', 'on-warn',
  'status-ok', 'on-ok', 'status-info', 'on-info',
  'chart-1', 'chart-2', 'chart-3',
];

export const decls = (vars, indent, prefix = '--fk-') =>
  Object.entries(vars)
    .map(([key, value]) => `${indent}${prefix}${key}: ${value};\n`)
    .join('');

function modeBody(mode, indent, withShadcn) {
  let out = decls(mode.colors, indent) + `${indent}color-scheme: ${mode.colorScheme};\n`;
  // Syntax colors for code, as variables, so that a page can color code
  // with the theme that is active.
  if (mode.syntax) out += decls(mode.syntax, indent, '--fk-syntax-');
  if (withShadcn) {
    const bridge = {};
    for (const [name, token] of Object.entries(SHADCN)) {
      if (mode.shadcn?.[name]) bridge[name] = mode.shadcn[name];
      else if (token in mode.colors) bridge[name] = `var(--fk-${token})`;
    }
    out += '\n' + decls(bridge, indent, '--');
  }
  return out;
}

// `scoped` writes the theme under [data-fk-theme="<name>"] and not under
// :root. A page can then load many themes and change between them, or show
// one theme inside an element.
export function themeCss(theme, withShadcn, scoped = false) {
  const { name, modes, fonts } = theme;
  const def = modes[theme.default];
  const body = (mode, indent) => modeBody(mode, indent, withShadcn);
  const root = scoped ? `[data-fk-theme="${name}"]` : ':root';
  const at = scoped ? root : '';
  // A mode is selected with data-theme="<mode>". Dark and light modes also
  // answer to the .dark and .light classes that shadcn projects use.
  const selectors = (key) => {
    const list = [`${at}[data-theme="${key}"]`];
    if (key !== theme.print) list.push(`${at}.${modes[key].colorScheme}`);
    return list.join(', ');
  };

  let css = banner(`the ${name} theme${withShadcn ? ' with shadcn variable names' : ''}${scoped ? `, under [data-fk-theme="${name}"]` : ''}`);
  css += `${root} {\n${decls(fonts, '  ')}`;
  // Tile fills are the same in each mode.
  if (theme.tiles) css += decls(theme.tiles, '  ', '--fk-tile-');
  if (theme.tileText) css += `  --fk-tile-text: ${theme.tileText};\n`;
  if (withShadcn) css += '  --radius: 0rem;\n';
  css += '}\n\n';
  css += `${root}, ${selectors(theme.default)} {\n${body(def, '  ')}}\n`;

  for (const [key, mode] of Object.entries(modes)) {
    if (key === theme.default || key === theme.print) continue;
    if (theme.followSystem && mode.colorScheme !== def.colorScheme) {
      css += `@media (prefers-color-scheme: ${mode.colorScheme}) {\n`;
      css += `  ${root}:not([data-theme]):not(.${def.colorScheme}) {\n${body(mode, '    ')}  }\n}\n`;
    }
    css += `${selectors(key)} {\n${body(mode, '  ')}}\n`;
  }
  if (theme.print) {
    const all = scoped ? root : ':root, [data-theme], .dark, .light';
    css += `@media print {\n  ${all} {\n${body(modes[theme.print], '    ')}  }\n}\n`;
  }
  return css;
}

// A Shiki (TextMate) theme for code blocks, from a mode's "syntax" colors.
// The background is not set: the page gives the code block its fill.
export function shikiTheme(theme, key) {
  const mode = theme.modes[key];
  const s = mode.syntax;
  const rule = (scope, foreground, fontStyle) => ({ scope, settings: { foreground, ...(fontStyle && { fontStyle }) } });
  return {
    name: `fluorokit-${theme.name}-${mode.colorScheme}`,
    type: mode.colorScheme,
    colors: { 'editor.foreground': mode.colors.text, 'editor.background': mode.colors.mantle },
    tokenColors: [
      { settings: { foreground: mode.colors.text } },
      rule(['comment', 'punctuation.definition.comment'], s.comment, 'italic'),
      rule(['punctuation', 'meta.brace', 'keyword.operator', 'meta.embedded punctuation'], s.punctuation),
      rule(['keyword', 'storage', 'storage.type', 'storage.modifier', 'keyword.operator.new', 'keyword.operator.expression', 'keyword.operator.logical.python', 'variable.language'], s.keyword),
      rule(['string', 'punctuation.definition.string', 'markup.inline.raw', 'markup.inserted'], s.string),
      rule(['constant.numeric', 'constant.language', 'markup.deleted'], s.number),
      rule(['constant.other', 'constant.character', 'variable.other.constant', 'support.constant', 'variable.other.enummember'], s.constant),
      rule(['entity.name.function', 'support.function', 'meta.function-call entity.name', 'markup.heading'], s.function),
      rule(['entity.name.type', 'entity.name.class', 'entity.name.namespace', 'support.type', 'support.class', 'entity.other.inherited-class'], s.type),
      rule(['entity.name.tag', 'punctuation.definition.tag'], s.tag),
      rule(['entity.other.attribute-name', 'support.type.property-name', 'meta.object-literal.key', 'entity.name.tag.yaml', 'variable.other.property'], s.attribute),
      rule(['variable', 'variable.parameter', 'variable.other.readwrite'], mode.colors.text),
      rule(['markup.bold'], mode.colors.text, 'bold'),
      rule(['markup.italic'], mode.colors.text, 'italic'),
    ],
  };
}
